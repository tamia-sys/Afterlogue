const {test,expect}=require('@playwright/test');

test('Approved landing concept has tagline-led hero, matching logo and arrow-free CTAs',async({page})=>{
 await page.goto('index.html');
 await expect(page.locator('#welcome-title')).toHaveText("A film ends. The conversation doesn't.");
 await expect(page.locator('.welcome-eyebrow')).toHaveText('PERSONALIZED FILM & TV DISCOVERY');
 await expect(page.locator('.hero-copy')).toContainText('Five recommendations, shaped by your taste.');
 const start=page.locator('#hero-cta');
 await expect(start).toHaveText('Start discovering');
 await expect(start).toHaveAttribute('href','log.html?guest=1');
 await expect(page.locator('.bottom-cta')).toHaveText('Start discovering');
 await expect(page.locator('.bottom-cta')).toHaveAttribute('href','log.html?guest=1');
 await expect(page.locator('.header-signin')).toHaveAttribute('href','signup.html?mode=signin');
 await expect(page.locator('header .wordmark')).toHaveAttribute('href','index.html');
 const sameColor=await page.evaluate(()=>{
  const logo=getComputedStyle(document.querySelector('.wordmark')).color;
  const heading=getComputedStyle(document.querySelector('#welcome-title')).color;
  return logo===heading;
 });
 expect(sameColor).toBe(true);
 await expect(page.locator('.feature-wrap,.features')).toHaveCount(0);
});
test('The landing rating demo checks and dims only the film selected',async({page})=>{
 await page.goto('index.html');
 const moonlight=page.locator('#rate-posters [data-film="moonlight"]');
 const boyhood=page.locator('#rate-posters [data-film="boyhood"]');
 const loved=page.locator('#rating-controls [data-reaction="Loved"]');
 await expect(loved).toBeDisabled();
 await moonlight.click();
 await expect(loved).toBeEnabled();
 await loved.click();
 await expect(moonlight).toHaveClass(/is-rated/);
 await expect(moonlight.locator('.rating-tick')).toBeVisible();
 await expect(boyhood).not.toHaveClass(/is-rated/);
 await expect(page.locator('#rating-status')).toContainText('Moonlight');
 await boyhood.click();
 await page.locator('#rating-controls [data-reaction="Okay"]').click();
 await expect(boyhood).toHaveClass(/is-rated/);
 await moonlight.click();
 await expect(loved).toHaveClass(/is-active/);
 await page.reload();
 await expect(moonlight).not.toHaveClass(/is-rated/);
});
test('Discovery preview uses the clicked film and only illustrative controls',async({page})=>{
 await page.goto('index.html');
 const card=page.locator('#discover-posters [data-film="perfect"]');
 const cover=await card.locator('img').getAttribute('src');
 await card.click();
 await expect(page.locator('#preview-backdrop')).toHaveClass(/is-open/);
 await expect(page.locator('.detail-copy h2')).toHaveText('Perfect Days');
 await expect(page.locator('.detail-poster img')).toHaveAttribute('src',cover);
 await expect(page.locator('.detail-synopsis')).toContainText('Hirayama');
 await expect(page.locator('.mock-actions .mock-action')).toHaveCount(5);
 await expect(page.locator('.mock-actions button')).toHaveCount(0);
 await page.keyboard.press('Escape');
 await expect(page.locator('#preview-backdrop')).not.toHaveClass(/is-open/);
 await page.locator('#discover-posters [data-film="sentimental"]').click();
 await expect(page.locator('.detail-copy h2')).toHaveText('Sentimental Value');
 await expect(page.locator('.detail-synopsis')).toContainText('sisters');
 await page.locator('#modal-close').click();
});
